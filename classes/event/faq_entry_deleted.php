declare(strict_types=1);

namespace local_wb_faq\event;

use context_system;

/**
 * Triggered when a FAQ category or question was deleted.
 *
 * @package    local_wb_faq
 * @copyright  2022 Wunderbyte GmbH <info@wunderbyte.at>
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class faq_entry_deleted extends \core\event\base {
    /**
     * Creates the event for a record.
     *
     * @param int $id
     * @return self
     */
    public static function create_for(int $id): self {
        return self::create(['objectid' => $id, 'context' => context_system::instance()]);
    }

    /**
     * Init method.
     *
     * @return void
     */
    protected function init() {
        $this->data['crud'] = 'd';
        $this->data['edulevel'] = self::LEVEL_OTHER;
        $this->data['objecttable'] = 'local_wb_faq_entry';
    }

    /**
     * Returns description of what happened.
     *
     * @return string
     */
    public function get_description() {
        return "The user with id '$this->userid' has deleted the faq entry with id '$this->objectid'.";
    }

    /**
     * Return localised event name.
     *
     * @return string
     */
    public static function get_name() {
        return get_string('faqentrydeleted', 'local_wb_faq');
    }

    /**
     * Returns the mapping of the object id for backup and restore.
     *
     * @return int
     */
    public static function get_objectid_mapping() {
        return self::NOT_MAPPED;
    }
}
